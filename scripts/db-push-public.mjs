// Merges every service's prisma/schema.prisma into one schema and pushes it to
// the shared database's **public** schema (single-schema layout — no more
// per-service Postgres schemas).
//
// Why merged: each service still owns its own Prisma client, but `prisma db push`
// assumes it owns everything in the target schema — pushing per-service against a
// shared schema would drop the other services' tables. One merged push sees the
// whole picture.
//
// Usage:  node scripts/db-push-public.mjs            (uses DATABASE_URL, or
//         falls back to apigateway-service/.env)
import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { resolveDatabaseUrl } from './lib/resolveDatabaseUrl.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const services = fs
  .readdirSync(path.join(root, 'services'))
  .map((s) => path.join(root, 'services', s, 'prisma', 'schema.prisma'))
  .filter((p) => fs.existsSync(p));

const seenModels = new Map();
const parts = [];
for (const file of services) {
  // Strip each service's generator/datasource blocks — the merged file has its own.
  const body = fs
    .readFileSync(file, 'utf8')
    .replace(/^(generator|datasource)\s+\w+\s*\{[^}]*\}\s*/gm, '');
  for (const m of body.matchAll(/^(?:model|enum)\s+(\w+)/gm)) {
    const prev = seenModels.get(m[1]);
    if (prev) throw new Error(`Duplicate model "${m[1]}" in ${file} (already defined in ${prev})`);
    seenModels.set(m[1], file);
  }
  parts.push(`// ---- from ${path.relative(root, file).replace(/\\/g, '/')} ----\n${body.trim()}`);
}

const merged = `// GENERATED by scripts/db-push-public.mjs — do not edit by hand.
datasource db {
  provider = "postgresql"
  url      = env("DATABASE_URL")
}

${parts.join('\n\n')}
`;

const outDir = path.join(root, 'prisma');
fs.mkdirSync(outDir, { recursive: true });
const outFile = path.join(outDir, 'merged.prisma');
fs.writeFileSync(outFile, merged);
console.log(`Merged ${services.length} service schemas (${seenModels.size} models) -> prisma/merged.prisma`);

execSync(`npx prisma db push --schema "${outFile}" --skip-generate`, {
  cwd: root,
  stdio: 'inherit',
  env: { ...process.env, DATABASE_URL: resolveDatabaseUrl() },
});
